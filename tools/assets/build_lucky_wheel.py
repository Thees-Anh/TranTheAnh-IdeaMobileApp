"""Build offline Wheel from preserved artist HTML; retain SVG, styling and animation math."""
from pathlib import Path
import re
import subprocess

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'design/prototypes/gacha/lucky_wheel.html'
TARGET=ROOT/'shared/src/androidMain/assets/gacha'


def main():
    source=SOURCE.read_text(encoding='utf-8')
    css=re.search(r'<style id="lucky-wheel-styles">(.*?)</style>',source,re.S).group(1)
    svg=re.search(r'<svg id="lucky-wheel-svg".*?</svg>',source,re.S).group(0)
    cards=source[source.index('<div class="grid grid-cols-3 gap-2 w-full mb-3">'):source.index('<div id="jackpot-final-message"')]
    constants=source[source.index('const WHEEL_SLOTS'):source.index('// 3.',source.index('const UNLOCKABLE_PETS'))]
    # No economy state, RNG or studio actions are packaged. Display odds await backend initialization.
    constants=constants[:constants.index('};',constants.index('const UNLOCKABLE_PETS'))+2]
    constants=re.sub(r'probability: \d+',"probability: '?'",constants)
    constants=re.sub(r'amount: \d+','amount: 0',constants)
    draw=source[source.index('function renderWheelSVG'):source.index('// 6.',source.index('function renderWheelSVG'))]
    math=source[source.index('function getPointedSlotIndexFromAngle'):source.index('function spinLuckyWheel')]
    controller=(ROOT/'design/prototypes/gacha/lucky_wheel_controller.js').read_text(encoding='utf-8')
    runtime=f'''<!DOCTYPE html>
<!-- Generated by tools/assets/build_lucky_wheel.py; artwork preserved in design/prototypes/gacha. -->
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; font-src 'self'; img-src 'self'; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'">
<title>Lucky Wheel</title><link rel="stylesheet" href="lucky_wheel.css"><style>{css}
@font-face{{font-family:Quicksand;src:url('quicksand.ttf') format('truetype');font-weight:300 800;font-display:swap}}
html,body{{margin:0;width:100%;height:100vh;overflow:hidden}}main{{height:100vh;width:100%;position:relative}}
#lucky-wheel-svg{{display:block;width:100%;height:100%;overflow:hidden}}[hidden]{{display:none!important}}
main{{isolation:isolate;background:radial-gradient(ellipse at 50% 43%,#fff5cc 0%,#ffe2ed 38%,#dbb5eb 76%,#b89cdb 100%)}}
main::before{{content:"";position:absolute;inset:0;z-index:-1;pointer-events:none;background-image:radial-gradient(circle,#fff9df 1.5px,transparent 2px),radial-gradient(circle,#ffffffaa 1px,transparent 2px);background-size:53px 67px,89px 103px;background-position:12px 17px,37px 45px}}
main::after{{content:"";position:absolute;left:8%;right:8%;bottom:8%;height:12%;border-radius:50%;background:radial-gradient(ellipse,#a76abe55,transparent 70%);z-index:-1;pointer-events:none}}
#lucky-wheel-svg{{filter:drop-shadow(0 12px 14px #7d459433)}}
#wheel-status-banner{{border-radius:14px 14px 0 0;padding:8px;box-sizing:border-box;background:#fff5f8dc!important;color:#4a2511}}
#wheel-status-banner{{position:absolute;bottom:0;width:100%;text-align:center;background:#fff5f8;font-size:12px;font-weight:700}}
#pet-unlock-stage{{position:absolute;inset:0;display:flex;flex-direction:column;justify-content:center;padding:12px;background:#fff5f8f5;text-align:center}}
@media(prefers-reduced-motion:reduce){{*,*::before,*::after{{animation:none!important;transition:none!important}}}}
.reduced-motion *{{animation:none!important;transition:none!important}}
</style></head><body><main aria-label="Lucky Wheel animation">{svg}
<div id="wheel-status-banner">Ready</div><section id="pet-unlock-stage" hidden>{cards}
<div id="jackpot-final-message" aria-live="polite"></div></section></main>
<script>{constants}\n{draw}\n{math}\n{controller}</script></body></html>'''
    assert not any(s in runtime for s in ['Math.random','playerResources','onclick=','rollWeightedSlotIndex','craftPetWithShards'])
    (TARGET/'lucky_wheel.html').write_text(runtime,encoding='utf-8')
    build=ROOT/'build/gacha-toolchain'
    (build/'wheel-input.css').write_text('@tailwind base;\n@tailwind components;\n@tailwind utilities;\n')
    config=build/'wheel-tailwind.config.cjs'
    config.write_text('module.exports={content:['+repr(SOURCE.as_posix())+'],theme:{extend:{borderWidth:{3:"3px"}}}};')
    subprocess.run(['node',str(build/'node_modules/tailwindcss/lib/cli.js'),'-c',str(config),'-i',str(build/'wheel-input.css'),
                    '-o',str(TARGET/'lucky_wheel.css'),'--minify'],check=True,cwd=ROOT)
    print('PASS offline Wheel SVG, pet cards, deterministic adapter and local CSS')


if __name__=='__main__':
    main()
