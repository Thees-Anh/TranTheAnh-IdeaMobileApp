"""Generate the offline server-driven stage from the preserved artist HTML.

Install pinned build tool: npm install --prefix build/gacha-toolchain tailwindcss@3.4.17 --no-audit --no-fund
Then run this file from the project root. No CDN is used at app runtime.
"""
from pathlib import Path
import re
import shutil
import subprocess
import json

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'design/prototypes/gacha/item_case_opening.html'
TARGET = ROOT / 'shared/src/androidMain/assets/gacha'


def main():
    source = SOURCE.read_text(encoding='utf-8')
    css = re.search(r'<style id="pawquest-gacha-styles">(.*?)</style>', source, re.S).group(1)
    stage = source[source.index('<div id="gacha-stage-container"'):source.index('<div id="reward-reveal-modal"')]
    stage = re.sub(r'<!-- Trạng thái hướng dẫn.*?(?=<!-- =)', '', stage, flags=re.S)
    # The reward overlay begins inside the stage. Native UI owns real balances
    # and confirmed rewards; this stage-only document has no economy controls.
    stage += '</div>'
    script = source[source.index('const RARITY_CONFIG'):source.index('// 3. HỆ THỐNG ÂM THANH')]
    eligible = {item['id'] for item in json.loads((ROOT / 'design/assets/decor/catalog.json').read_text(encoding='utf-8'))}
    script = '\n'.join(line for line in script.splitlines()
                       if '{ id:' not in line or re.search(r"id: '([^']+)'", line).group(1) in eligible)
    constants = source[source.index('const TOTAL_REEL_CARDS'):source.index('let userCoins')]
    reel = source[source.index('function buildReelCards'):source.index('// 5. QUY TRÌNH MỞ RƯƠNG')]
    controller = (ROOT / 'design/prototypes/gacha/item_case_controller.js').read_text(encoding='utf-8')
    reel = reel.replace("const tier = rollRarityTier('random');", '// Cosmetic filler only; never determines the confirmed winner.')
    reel = reel.replace('pickRandomItemByRarity(tier)', 'CASE_DISPLAY_ITEMS[Math.floor(Math.random() * CASE_DISPLAY_ITEMS.length)]')
    # Boundary comments can contain the source script's separators, which are JS comments.
    runtime = f'''<!DOCTYPE html>
<!-- Generated by tools/assets/build_item_case.py from the preserved design input. -->
<html lang="en"><head><meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; font-src 'self'; img-src 'self'; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'">
<title>Mystery Case preview</title><link rel="stylesheet" href="item_case.css">
<style>{css}
@font-face {{font-family:Quicksand;src:url('quicksand.ttf') format('truetype');font-weight:300 800;font-display:swap}}
html,body,main{{width:100%;height:100vh;margin:0;overflow:hidden}}
#gacha-stage-container{{min-height:0;height:100vh;padding:8px;justify-content:space-around}}
#cs2-viewport-box{{height:148px}} #chest-svg-container{{width:min(240px,85vw);height:140px}}
/* The same renderer expands when hosted in the full-screen opening surface. */
@media(min-height:480px){{
 #cs2-viewport-box{{height:clamp(200px,34vh,300px)}}
 .cs2-reel-card{{width:clamp(140px,40vw,180px);height:clamp(176px,29vh,264px);padding:12px 8px}}
 .cs2-reel-card .text-3xl{{font-size:clamp(40px,12vw,60px);line-height:1.1}}
 .cs2-reel-card .text-\\[10px\\]{{font-size:12px}}
 #chest-svg-container{{width:min(300px,85vw);height:clamp(170px,30vh,260px)}}
}}
@media(prefers-reduced-motion:reduce){{*,*::before,*::after{{animation:none!important;transition:none!important}}}}
</style></head><body><main aria-label="Mystery Case artwork">{stage}</main>
<script>{script}
{constants}
let CASE_DISPLAY_ITEMS = GACHA_ITEMS_POOL;
{reel}
{controller}
</script></body></html>'''
    assert 'startGachaSpin' not in runtime and 'userCoins' not in runtime and 'onclick=' not in runtime
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / 'item_case_opening.html').write_text(runtime, encoding='utf-8')
    shutil.copyfile(ROOT / 'shared/src/commonMain/composeResources/font/quicksand.ttf', TARGET / 'quicksand.ttf')
    build = ROOT / 'build/gacha-toolchain'
    (build / 'input.css').write_text('@tailwind base;\n@tailwind components;\n@tailwind utilities;\n', encoding='utf-8')
    config = build / 'tailwind.config.cjs'
    # Includes all static and template-generated class names in the supplied design.
    config.write_text('module.exports={content:[' + repr(SOURCE.as_posix()) + '],theme:{extend:{borderWidth:{3:"3px"}}}};', encoding='utf-8')
    subprocess.run(['node', str(build / 'node_modules/tailwindcss/lib/cli.js'), '-c', str(config),
                    '-i', str(build / 'input.css'), '-o', str(TARGET / 'item_case.css'), '--minify'], check=True, cwd=ROOT)
    shutil.copyfile(build / 'node_modules/tailwindcss/LICENSE', ROOT / 'docs/licenses/tailwindcss.txt')
    print('PASS generated offline Mystery Case stage, utility CSS and local font')


if __name__ == '__main__':
    main()
