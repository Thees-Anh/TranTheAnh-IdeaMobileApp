"""Generate the migration that blocks Mystery Box and Lucky Wheel draws while the pet is hungry or thirsty.

The two public RPC bodies are copied verbatim from their original migrations and receive one
inserted guard right after request-ID recovery, so a retried, already-committed draw still
returns its receipt. Run with --check to verify the committed migration is up to date.
"""
import argparse
from pathlib import Path

ROOT = next(parent for parent in Path(__file__).resolve().parents if (parent / 'settings.gradle.kts').is_file())
OUTPUT = ROOT / 'supabase/migrations/20261112003300_gacha_pet_care_gate.sql'
THRESHOLD = 25  # Same "hungry/thirsty" line as reminders and the mood icon (≤25).


def function_body(path: Path, header: str) -> str:
    text = path.read_text(encoding='utf-8')
    start = text.index(header)
    end = text.index('end $$;', start) + len('end $$;')
    return text[start:end]


def insert_after(body: str, anchor: str, addition: str) -> str:
    assert body.count(anchor) == 1, anchor
    return body.replace(anchor, anchor + addition)


def build() -> str:
    case = function_body(ROOT / 'supabase/migrations/20261110002600_secure_item_case_open.sql',
                         'create function public.item_case_open(')
    case = case.replace('create function public.item_case_open(', 'create or replace function public.item_case_open(', 1)
    case = case.replace('stamp timestamptz; retry_seconds integer;', 'stamp timestamptz; retry_seconds integer; need text;', 1)
    case = insert_after(case, """        return pawquest_private.item_case_response(previous.id);
    end if;
""", """
    -- A hungry or thirsty pet must be cared for first (checked after recovery, before throttle or charge).
    need:=pawquest_private.gacha_care_block(actor);
    if need is not null then return jsonb_build_object('status','pet_needs_care','receipt',null,'need',need); end if;
""")

    wheel = function_body(ROOT / 'supabase/migrations/20261110002800_lucky_wheel.sql',
                          'create function public.lucky_wheel_spin(')
    wheel = wheel.replace('create function public.lucky_wheel_spin(', 'create or replace function public.lucky_wheel_spin(', 1)
    wheel = wheel.replace('food record; owned integer; winning_sector text;', 'food record; owned integer; winning_sector text; need text;', 1)
    wheel = insert_after(wheel, """  return pawquest_private.wheel_response(prior.id);
 end if;
""", """ -- A hungry or thirsty pet must be cared for first (checked after recovery, before throttle or charge).
 need:=pawquest_private.gacha_care_block(actor);
 if need is not null then return jsonb_build_object('status','pet_needs_care','need',need); end if;
""")

    return f"""-- Generated by tools/balance/generate_gacha_care_gate.py; do not edit by hand.
-- Mystery Box and Lucky Wheel draws are refused while the pet is hungry or thirsty
-- (Hunger or Water ≤ {THRESHOLD} after time-based decay). Nothing is charged, throttled or drawn.
begin;

create function pawquest_private.gacha_care_threshold() returns integer
language sql immutable set search_path='' as $$ select {THRESHOLD} $$;

create function pawquest_private.gacha_care_block(p_actor uuid) returns text
language plpgsql security definer set search_path='' as $$
declare hunger_now integer; water_now integer; line integer:=pawquest_private.gacha_care_threshold();
begin
    if p_actor is null or p_actor is distinct from auth.uid() then
        raise exception 'Authentication required' using errcode='42501'; end if;
    -- Apply elapsed decay exactly like Pet Home does before judging the pet's needs.
    perform public.pet_state();
    select hunger,hydration into hunger_now,water_now from public.pets where user_id=p_actor;
    if not found then return null; end if;
    return case when hunger_now<=line and water_now<=line then 'hungry_thirsty'
        when hunger_now<=line then 'hungry' when water_now<=line then 'thirsty' end;
end $$;
revoke all on function pawquest_private.gacha_care_threshold(),pawquest_private.gacha_care_block(uuid)
    from public,anon,authenticated,service_role;

{case}

{wheel}

comment on function pawquest_private.gacha_care_block(uuid) is
    'Returns hungry/thirsty/hungry_thirsty when Mystery Box and Lucky Wheel draws must wait for pet care, else null.';
commit;
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sql = build()
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != sql:
            raise SystemExit(f'{OUTPUT.name} is out of date; run without --check')
        print(f'PASS {OUTPUT.name} matches the generator')
    else:
        OUTPUT.write_text(sql, encoding='utf-8', newline='\n')
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
