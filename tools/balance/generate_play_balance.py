"""Generate Play costs and forward migration 018; installed migrations stay unchanged."""
import json,sys
from pathlib import Path
ROOT=next(parent for parent in Path(__file__).resolve().parents if (parent / 'settings.gradle.kts').is_file())
values=json.loads((ROOT/'config/play-balance.json').read_text())
assert set(values)=={'energyCost','hungerCost','waterCost'}
assert all(type(v) is int and 0<v<=100 for v in values.values())
kotlin='// Generated by tools/balance/generate_play_balance.py.\npackage com.pawquest.domain.model\n\nobject PlayBalance {\n'
kotlin+=''.join(f'    const val {key}: Int = {value}\n' for key,value in values.items())+'}\n'
sql=(ROOT/'supabase/templates/play.sql.in').read_text(encoding='utf-8').replace('@@PLAY_JSON@@',json.dumps(values,separators=(',',':')))
for path,value in {ROOT/'shared/src/commonMain/kotlin/com/pawquest/domain/model/PlayBalance.kt':kotlin,
                   ROOT/'supabase/migrations/20261106001800_play_costs.sql':sql}.items():
    if '--check' in sys.argv:assert path.read_text(encoding='utf-8')==value,f'Stale {path}'
    else:path.write_text(value,encoding='utf-8')
print('PASS Play balance generation check' if '--check' in sys.argv else 'Generated Play costs and migration 018')
