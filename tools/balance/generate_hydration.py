"""Generate hydration constants/migration 014 without changing installed migrations."""
import json,sys
from pathlib import Path
ROOT=next(parent for parent in Path(__file__).resolve().parents if (parent / 'settings.gradle.kts').is_file())
values=json.loads((ROOT/'config/hydration-balance.json').read_text())
assert all(type(v) is int and 0<v<=100 for v in values.values())
kotlin='// Generated by tools/balance/generate_hydration.py.\npackage com.pawquest.domain.model\n\nobject HydrationBalance {\n'
kotlin+=''.join(f'    const val {key}: Int = {value}\n' for key,value in values.items())+'}\n'
sql=(ROOT/'supabase/templates/hydration.sql.in').read_text(encoding='utf-8').replace('@@HYDRATION_JSON@@',json.dumps(values,separators=(',',':')))
for path,value in {ROOT/'shared/src/commonMain/kotlin/com/pawquest/domain/model/HydrationBalance.kt':kotlin,
                   ROOT/'supabase/migrations/20261106001400_pet_hydration.sql':sql}.items():
    if '--check' in sys.argv:assert path.read_text(encoding='utf-8')==value,f'Stale {path}'
    else:path.write_text(value,encoding='utf-8')
print('PASS hydration generation check' if '--check' in sys.argv else 'Generated hydration constants and migration 014')
