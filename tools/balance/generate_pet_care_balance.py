"""Generate shared constants and migration 009 from one reviewed balance source."""
import argparse
import json
from pathlib import Path

ROOT=next(parent for parent in Path(__file__).resolve().parents if (parent / 'settings.gradle.kts').is_file())
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    values=json.loads((ROOT/'config/pet-care-balance.json').read_text())
    assert all(type(v) is int and v>0 for v in values.values())
    assert values['statMax']==100 and values['starterFood']<=1000000
    kotlin='// Generated by tools/balance/generate_pet_care_balance.py; edit config/pet-care-balance.json.\npackage com.pawquest.domain.model\n\nobject PetCareBalance {\n'
    kotlin+=''.join(f'    const val {key}: Int = {value}\n' for key,value in values.items())+'}\n'
    sql=(ROOT/'supabase/templates/pet_care.sql.in').read_text().replace('@@BALANCE_JSON@@',json.dumps(values,separators=(',',':')))
    outputs={ROOT/'shared/src/commonMain/kotlin/com/pawquest/domain/model/PetCareBalance.kt':kotlin,
             ROOT/'supabase/migrations/20261105000900_pet_care.sql':sql}
    for path,value in outputs.items():
        if args.check:
            assert path.read_text(encoding='utf-8')==value, f'Stale generated output: {path.name}'
        else:
            path.write_text(value,encoding='utf-8')
    print('PASS Pet care balance outputs match canonical configuration' if args.check else 'Generated Pet care balance outputs')
if __name__=='__main__':
    main()
